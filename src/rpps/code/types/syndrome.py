import itertools
from math import comb

import numpy as np

from ._code import _code, register

MAX_CHECK_BITS = 24 # Table of 2^(n-k) syndromes

@register("syndrome")
class syndrome(_code):
    """Hard decoder of a linear block code by syndrome lookup: corrects every pattern of up to `t` bit errors

    Built from the code (`from_encoder`): the table maps each syndrome to the lightest error pattern that gives it.
    t defaults to the code's own (d_min - 1)//2, found by listing the codewords (k <= 20), or the code's `t`.
    A syndrome of no pattern within t is a detected failure: `errors` is -1 for that word and its message bits are
    returned as received. Soft input is hard decided first. The message is the first k bits of each word.
    """
    @classmethod
    def from_encoder(cls, log, enc, t=None):
        return cls(log, np.asarray(enc.generator), np.asarray(enc.check).T, t if t is not None else getattr(enc, "t", None))

    def __init__(self, log, G, H, t=None):
        G, H = np.asarray(G, dtype=np.uint8), np.asarray(H, dtype=np.uint8)
        k, n = G.shape
        r = H.shape[0]
        if r > MAX_CHECK_BITS:
            raise ValueError(f"Syndrome table needs 2^{r} entries: too many (limit 2^{MAX_CHECK_BITS})")
        super().__init__(log, None, k, n)
        self.H = H
        self.t = min_distance_t(G) if t is None else int(t)
        self._weights = 1 << np.arange(r - 1, -1, -1)
        self.weight = np.full(1 << r, -1, dtype=np.int64) # Error weight per syndrome, -1: not within t
        self.pattern = np.zeros((1 << r, n), dtype=np.uint8)
        self.weight[0] = 0
        cols = (H.astype(np.int64) * self._weights[:, None]).sum(axis=0) # Syndrome of each single-bit error
        for w in range(1, self.t + 1):
            if comb(n, w) > 1 << 22:
                raise ValueError(f"t={self.t}: too many error patterns of weight {w} in {n} bits")
            for pos in itertools.combinations(range(n), w):
                s = int(np.bitwise_xor.reduce(cols[list(pos)]))
                if self.weight[s] < 0:
                    self.weight[s] = w
                    self.pattern[s, list(pos)] = 1

    def decode(self, bits, soft=None):
        x = np.asarray(bits)
        if soft or (soft is None and x.dtype.kind == "f"):
            x = x < 0
        x = x.astype(np.uint8)
        words = x[:len(x)//self.den*self.den].reshape(-1, self.den)
        s = ((words.astype(np.int64) @ self.H.T.astype(np.int64)) % 2) @ self._weights
        self.errors = self.weight[s].astype(int)
        fixed = words ^ self.pattern[s]
        return fixed[:, :self.num].reshape(-1).astype(bool)

def min_distance_t(G):
    """(d_min - 1)//2 of the code generated by G, from all its codewords"""
    G = np.asarray(G, dtype=np.uint8)
    k = G.shape[0]
    if k > 20:
        raise ValueError(f"k={k}: too many codewords to find the minimum distance, give t")
    msgs = ((np.arange(1, 1 << k)[:, None] >> np.arange(k - 1, -1, -1)) & 1).astype(np.uint8)
    d = int(((msgs @ G) % 2).sum(axis=1).min())
    return (d - 1)//2
